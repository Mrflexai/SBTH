import java.time.LocalDate

fun MissionEntity.versModele(): Mission = Mission(
    id = id,
    numeroCac = numeroCac,
    dateReception = LocalDate.ofEpochDay(dateReception),
    heureAppel = heureAppel,
    chauffeur = chauffeur,
    immatDepanneuse = immatDepanneuse,
    beneficiaireNom = beneficiaireNom,
    beneficiaireTelephone = beneficiaireTelephone,
    vehiculeMarqueModele = vehiculeMarqueModele,
    vehiculeImmatriculation = vehiculeImmatriculation,
    villeDepart = villeDepart,
    lieuPriseEnCharge = lieuPriseEnCharge,
    villeDestination = villeDestination,
    lieuDestination = lieuDestination,
    motif = motif,
    heureDepart = heureDepart,
    heureArrivee = heureArrivee,
    heureChargement = heureChargement,
    heureLivraison = heureLivraison,
    kmDepart = kmDepart,
    kmArrivee = kmArrivee,
    distanceKm = distanceKm,
    kmFacturables = kmFacturables,
    observations = observations,
    statut = StatutMission.entries.firstOrNull { it.name == statut } ?: StatutMission.RECUE,
    tarifBase = tarifBase,
    tarifKm = tarifKm,
    supplementNuit = supplementNuit,
    supplementWeekend = supplementWeekend,
    fraisAutoroute = fraisAutoroute,
    fraisSupplementaires = fraisSupplementaires,
    fraisSupplementairesLibelle = fraisSupplementairesLibelle,
    montantRegle = montantRegle,
    dateReglement = dateReglement?.let(LocalDate::ofEpochDay),
    referenceReglement = referenceReglement,
    creeLe = creeLe,
    modifieLe = modifieLe,
)

